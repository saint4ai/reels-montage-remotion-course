export const WORDS23: Word[] = raw.reduce<Word[]>((out, w, i) => {
  const fx = FIX[i];
  if (fx === null && out.length) { out[out.length - 1] = {...out[out.length - 1], end: w.end}; return out; }
  out.push({text: fx ?? w.text, start: w.start, end: Math.max(w.end, w.start + 0.05)});
  return out;
}, []).map((w, i, a) => (i > 0 && w.start < a[i - 1].end ? {...w, start: a[i - 1].end} : w));

// Момент слова по тексту: n-е вхождение (с 0), без знаков препинания
export const at23 = (text: string, n = 0) => {
  const hits = WORDS23.filter((w) => w.text.replace(/[.,:!?—«»]/g, '').trim().toLowerCase() === text.toLowerCase());
  if (!hits[n]) throw new Error(`нет слова «${text}» #${n}`);
  return hits[n].start;
};
